# Tipo de dado Bool (Boolean)

# Ao questionar algo em um programa, só existem duas respostas possíveis:
# SIm (TRUE) ou não (FALSE). Existem vários operadores para "questionar"
# Dentre eles o '==', que é um operador lógico que questiona se um valor é igual a outro

print(10 == 10) # 10 é igual a 10? Sim = True (Verdadeiro)
print(10 == 11) # 10 é igual a 11? Não = False (Falso)

#Usando Type
print(type(10 == 11))
print(type(False))