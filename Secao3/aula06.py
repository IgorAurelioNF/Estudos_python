# Conversão de tipos, Coerção, type convertion, typecasting, coercion
# É o ato de converter um tipo em outro tipo imutável e primitivo:
# str, int, float, bool

# print('1' + 1) Isso irá ocorrer um erro, pois  são duas variáveis primitivas diferentes

print('Inteiro: 1 + 1 =', int('1') + 1)
print('Float: 1 + 1 =', float('1') + 1)
print('String: 1 + 1 =', str(1) + 'B')
print('Boolean: Str vazia = ', bool(''))

