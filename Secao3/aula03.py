"""
Python = Linguagem de programação
Tipo de tipagem = Dinânmica/ Forte
str -> string -> texto
Strings são textos que estão dentro de aspas
"""

# Aspas simples
print('Hello, world!')

# Aspas duplas
print("Ígor Aurélio das Neves Ferreira")

# Aspas duplas + simples
print('Ígor "Ferreira"')

# Escape
print("Ígor \"Ferreira\"")

# r -> Usado em expressão regulares, mostra o Caracter de Escape
print(r'Igor \'Ferreira\'')

# PRÁTICA
print(1, 'Michelle da "Silva"', sep=('-'))

print('XXXXXXX', 'Y', 'ZZZZZZ " ZZZZZZZZ')