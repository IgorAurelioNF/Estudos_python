#Tipos int e float

# int -> Número Inteiro
# O tipo int representa qualquer número
# positivo ou negativo. Int sem sinal é considerado positivo
print(11)
print(-11)
print(0)

# float -> Número com ponto flutuante
# O tipo float presenta qualquer número
# positivo ou negativo com ponto flutuante
# Utilizado com ponto '.'
print(1.1)
print(-1.1)
print(0.1)

# A classe/função type mostra o tipo que o Python inferiu no valor
print(type('Igor'))
print(type(1))
print(type(1.1), type(-1.1), type(0.0))
